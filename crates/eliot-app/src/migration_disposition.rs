/// Fail-closed startup check over [`MIGRATION_LEDGER`]: the ledger must
/// be non-empty, name each source object once, carry complete fields and
/// well-formed hashes, and every `UNRESOLVED` row must carry the
/// [`MIGRATION_MAPPING_INCOMPLETE`] blocking code so retirement stays
/// blocked for exactly the affected scope. Any violation aborts startup.
pub fn migration_ledger_guard() -> Result<(), String> {
    if MIGRATION_LEDGER_PIN_COMMIT.len() != 40
        || !MIGRATION_LEDGER_PIN_COMMIT
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit())
    {
        return Err("migration ledger pin commit is not a commit id".to_owned());
    }
    if MIGRATION_LEDGER.is_empty() {
        return Err("migration ledger names no objects; W2 evidence is missing".to_owned());
    }
    for (index, row) in MIGRATION_LEDGER.iter().enumerate() {
        if row.source_object.is_empty()
            || row.source_path.is_empty()
            || row.source_semantics_owner.is_empty()
            || row.target_object.is_empty()
            || row.target_hash.is_empty()
            || row.verifier.is_empty()
            || row.reconciliation.is_empty()
            || row.rollback_boundary.is_empty()
            || row.cutover_receipt.is_empty()
        {
            return Err(format!("migration ledger row {index} has an empty field"));
        }
        if row.source_hash.len() != 64
            || !row.source_hash.bytes().all(|byte| byte.is_ascii_hexdigit())
        {
            return Err(format!(
                "migration ledger row {} has a malformed source hash",
                row.source_object,
            ));
        }
        if !ALL_OBJECT_DISPOSITIONS.contains(&row.disposition) {
            return Err(format!(
                "migration ledger row {} carries a disposition outside the closed vocabulary",
                row.source_object,
            ));
        }
        let unresolved = row.disposition == ObjectDisposition::Unresolved;
        let blocked = row.cutover_receipt == MIGRATION_MAPPING_INCOMPLETE;
        if unresolved != blocked {
            return Err(format!(
                "migration ledger row {} carries disposition {} but receipt {}; unresolved rows must carry the blocking code",
                row.source_object,
                row.disposition.as_str(),
                row.cutover_receipt,
            ));
        }
        if !unresolved && row.target_hash == "unresolved" {
            return Err(format!(
                "migration ledger row {} is resolved but names no target hash",
                row.source_object,
            ));
        }
        for prior in &MIGRATION_LEDGER[..index] {
            if prior.source_object == row.source_object {
                return Err(format!(
                    "migration ledger names {} twice; exactly one disposition per object",
                    row.source_object,
                ));
            }
        }
    }
    Ok(())
}
