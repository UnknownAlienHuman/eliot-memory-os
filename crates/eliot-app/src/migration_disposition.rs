//! Per-object migration disposition ledger (issue #1856; `I19.16`).
//!
//! One [`MigrationDisposition`] row per active top-level source object
//! of the four aggregate crates (`eliot-app`, `eliot-engine`,
//! `eliot-store`, `eliot-types`). Field order follows the `I19.16` schema:
//! source identity and hash, source semantics and owner, target identity
//! and hash, disposition, verifier refs, reconciliation, rollback or
//! no-return boundary, canonical cutover receipt.
//!
//! Every row is currently `UNRESOLVED`: the #1719 release-bundle cutover
//! has not landed and the #1696 behavior inventory is unpublished, so no
//! replacement owns any object yet. Per `I19.16`, missing mappings return
//! [`MIGRATION_MAPPING_INCOMPLETE`] and block retirement only for the
//! affected scope (`W3`: no deletion before replacement proof).
//!
//! `source_hash` is the sha256 of the source bytes at
//! [`MIGRATION_LEDGER_PIN_COMMIT`]: a single `.rs` file hashes to the
//! file bytes; a directory hashes to the concatenation of its nested
//! `.rs` file bytes in sorted relative-path order. A reviewer can
//! re-hash any `source_path` at the pinned commit to verify the row.

/// Blocking code returned for objects without a proven replacement
/// (`I19.16`: missing mappings block retirement for the affected scope).
pub const MIGRATION_MAPPING_INCOMPLETE: &str = "MIGRATION_MAPPING_INCOMPLETE";

/// Origin commit the `source_hash` values below were measured at.
pub const MIGRATION_LEDGER_PIN_COMMIT: &str = "f8811c6f497b19155bd62dea463ae86a3ae35c9c";

/// Per-object migration disposition (`I19.16` `MigrationDisposition`).
///
/// Exactly one row exists per active source object; the startup guard
/// [`migration_ledger_guard`] enforces uniqueness, complete fields,
/// well-formed hashes, and that every `UNRESOLVED` row carries the
/// [`MIGRATION_MAPPING_INCOMPLETE`] blocking code.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MigrationDisposition {
    /// Crate-qualified object name, e.g. `eliot-engine::admission`.
    pub source_object: &'static str,
    /// Repository-relative source path (file or directory).
    pub source_path: &'static str,
    /// sha256 of the source bytes at [`MIGRATION_LEDGER_PIN_COMMIT`].
    pub source_hash: &'static str,
    /// Behavior the object carries and its current semantic owner.
    pub source_semantics_owner: &'static str,
    /// Replacement object and owner, or the unresolved owner area.
    pub target_object: &'static str,
    /// Hash of the replacement object, or `unresolved`.
    pub target_hash: &'static str,
    /// Where this object stands in the migration.
    pub disposition: ObjectDisposition,
    /// Proof refs that must hold before the disposition can advance.
    pub verifier: &'static str,
    /// How provider memory and external effects reconcile on cutover.
    pub reconciliation: &'static str,
    /// Rollback window or no-return boundary for the cutover.
    pub rollback_boundary: &'static str,
    /// Canonical cutover receipt selecting the new owner, if any.
    pub cutover_receipt: &'static str,
}

/// `I19.16` disposition vocabulary: every active source object carries
/// exactly one of these.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ObjectDisposition {
    /// Behavior moved to the target object with equivalence proof.
    Migrated,
    /// Behavior folded into the target object with equivalence proof.
    Merged,
    /// Target object supersedes this one with equivalence proof.
    Superseded,
    /// Object retired with its evidence retained and receipt named.
    Archived,
    /// Object rejected from migration with reason recorded.
    Rejected,
    /// No proven replacement yet; retirement is blocked for this scope.
    Unresolved,
}

impl ObjectDisposition {
    /// Recorded disposition word, used in guard failure text.
    const fn as_str(self) -> &'static str {
        match self {
            Self::Migrated => "MIGRATED",
            Self::Merged => "MERGED",
            Self::Superseded => "SUPERSEDED",
            Self::Archived => "ARCHIVED",
            Self::Rejected => "REJECTED",
            Self::Unresolved => "UNRESOLVED",
        }
    }
}

